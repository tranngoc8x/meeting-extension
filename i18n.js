export const LANGUAGE_KEY = 'uiLanguage';
export const DEFAULT_LANGUAGE = 'vi';
export const SUPPORTED_LANGUAGES = Object.freeze(['vi', 'en']);

export function normalizeLanguage(value) {
  return value === 'en' ? 'en' : 'vi';
}

export async function loadLanguage(storage) {
  try {
    const saved = (await storage.get(LANGUAGE_KEY))[LANGUAGE_KEY];
    return normalizeLanguage(saved);
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export async function saveLanguage(storage, value) {
  const lang = normalizeLanguage(value);
  await storage.set({ [LANGUAGE_KEY]: lang });
  return lang;
}

